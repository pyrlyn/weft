//! The committed C header and C# bindings are what cbindgen and csbindgen generate from the
//! exports now; `WEFT_STUDIO_BLESS=1` rewrites them. A test rather than a script, so every
//! platform's test run catches a stale header with no tool to install.

// A test crate: a failed unwrap or panic is a failed test, which is the point.
#![allow(clippy::unwrap_used, clippy::panic)]

use std::path::{Path, PathBuf};
use std::process::Command;

use abi_drift::Drift;
use serde_json::Value as Json;

const DIR: &str = env!("CARGO_MANIFEST_DIR");

fn drift() -> Drift {
    Drift::new(DIR)
        .bless_from_env("WEFT_STUDIO_BLESS")
        .regenerate_with("WEFT_STUDIO_BLESS=1 cargo test -p weft-studio-ffi --test bindings")
}

#[test]
fn the_committed_c_header_is_what_cbindgen_generates() {
    let header = abi_drift::cbindgen_header(DIR, "cbindgen.toml", "src/lib.rs").unwrap();
    drift().check("include/weft_studio.h", &header).unwrap();
}

#[test]
fn the_committed_csharp_bindings_are_what_csbindgen_generates() {
    // csbindgen reads each file alone, so both modules with exports are listed.
    let builder = ["src/lib.rs", "src/abi.rs"]
        .iter()
        .fold(csbindgen::Builder::new(), |b, src| {
            b.input_extern_file(Path::new(DIR).join(src))
        })
        .csharp_dll_name("weft_studio_ffi")
        .csharp_namespace("WeftStudio.Native")
        .csharp_class_name("NativeMethods")
        .csharp_generate_const_filter(|name| name.starts_with("WS_"))
        // The surface is slint-bindings' handle; its C# side adopts it as an IntPtr
        // (`SlintHost.Adopt`), so it crosses here as an untyped pointer.
        .csharp_type_rename(|name| {
            if name == "SbHost" {
                "void".into()
            } else {
                name
            }
        })
        .csharp_file_header(
            "// Generated by csbindgen from crates/weft-studio-ffi: \
             WEFT_STUDIO_BLESS=1 cargo test -p weft-studio-ffi --test bindings. Do not edit.",
        );
    let scratch = Path::new(env!("CARGO_TARGET_TMPDIR")).join("weft-studio-NativeMethods.g.cs");
    let rendered = abi_drift::csbindgen_file(builder, scratch).unwrap();
    drift()
        .check("bindings/csharp/NativeMethods.g.cs", &rendered)
        .unwrap();
}

/// slint-bindings' C header in the checkout Cargo made of the pinned commit, which a macOS shell
/// includes beside this one.
fn slint_bindings_header() -> PathBuf {
    let out = Command::new(env!("CARGO"))
        .args(["metadata", "--format-version", "1"])
        .current_dir(DIR)
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let metadata: Json = serde_json::from_slice(&out.stdout).unwrap();
    let manifest = metadata["packages"]
        .as_array()
        .unwrap()
        .iter()
        .find(|p| p["name"] == "slint-bindings-ffi")
        .unwrap()["manifest_path"]
        .as_str()
        .unwrap()
        .to_owned();
    // `manifest_path` names Cargo.toml. Joining `..` onto that file fails in canonicalize,
    // because the file is not a directory, so the walk starts at the crate directory.
    // `crates/slint-bindings-ffi` sits two levels under the repo, beside `swift/`.
    Path::new(&manifest)
        .parent()
        .unwrap()
        .join("../../swift/Sources/CSlintBindings/slint_bindings.h")
        .canonicalize()
        .unwrap()
}

/// Both headers in one translation unit, in either order, as a shell's bridging header has them.
#[test]
fn the_header_compiles_beside_the_slint_bindings_header() {
    let ours = Path::new(DIR).join("include/weft_studio.h");
    let theirs = slint_bindings_header();
    for (first, second) in [(&ours, &theirs), (&theirs, &ours)] {
        let unit = format!(
            "#include \"{}\"\n#include \"{}\"\nint main(void) {{ return ws_api_version() == WS_API_VERSION ? 0 : 1; }}\n",
            first.display(),
            second.display()
        );
        let source = Path::new(env!("CARGO_TARGET_TMPDIR")).join("weft-studio-headers.c");
        std::fs::write(&source, unit).unwrap();
        let Ok(out) = Command::new("cc")
            .args(["-std=c11", "-Wall", "-Werror", "-fsyntax-only"])
            .arg(&source)
            .output()
        else {
            eprintln!("skipped: no C compiler (`cc`) on this machine");
            return;
        };
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}
